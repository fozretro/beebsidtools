#!/usr/bin/env node
/**
 * Retarget src.sids/goldenaxe/src/player.asm: org $4000, SID $FC20.
 * Pointer pages in EQUB stay $9x — reloc-data.mjs rewrites those after assemble.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const srcPath = process.argv[2];
const dstPath = process.argv[3];
if (!srcPath || !dstPath) {
  console.error("usage: from-listing.mjs <player.asm> <out.asm>");
  process.exit(1);
}

let src = readFileSync(srcPath, "utf8");

src = src.replace(
  `; Golden Axe player at runtime $9000 (Jeroen Tel / Maniacs of Noise).
; BeebDis listing of the 4K image init copies from file $10F0.
; Assembled with BeebAsm; do not hand-edit if you still need a
; byte-identical round-trip — change symbols/ctl and regenerate.`,
  `; Golden Axe player at runtime $4000 (BeebSID retarget of the $9000 listing).
; Generated by bin/from-listing.mjs — edit the HVSC listing, not this file.`,
);

src = src.replace(
  `SID     = $D400
SID_V1FREQHI = $D401
SID_V1PWLO = $D402
SID_V1PWHI = $D403
SID_V1CTRL = $D404
SID_V1AD = $D405
SID_V1SR = $D406
LD416   = $D416
LD417   = $D417
SID_MODEVOL = $D418`,
  `SID     = $FC20
SID_V1FREQHI = SID + 1
SID_V1PWLO = SID + 2
SID_V1PWHI = SID + 3
SID_V1CTRL = SID + 4
SID_V1AD = SID + 5
SID_V1SR = SID + 6
LD416   = SID + 22
LD417   = SID + 23
SID_MODEVOL = SID + 24`,
);

src = src.replace("        org     $9000", "        org     $4000");
src = src.replace(
  'SAVE "../out/player.bin",BeebDisStartAddr,BeebDisEndAddr',
  'SAVE "player.bin",BeebDisStartAddr,BeebDisEndAddr',
);

mkdirSync(dirname(dstPath), { recursive: true });
writeFileSync(dstPath, src);
console.log(`wrote ${dstPath}`);
